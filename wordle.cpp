bool isVALID(std::string guess){

    if(guess.length() < 5){

        switch(language){
            case 0: 
                std::cout << "\033[2K" << "ERROR: not enough letters"; 
                break;
            case 1: 
                std::cout << "\033[2K" << "ERRORE: non abbastanza lettere"; 
                break;
        }

        return 0;
    }
    
    else if(guess.length() > 5){

        switch(language){
            case 0:
                std::cout << "\033[2K" << "ERROR: too many letters";
                break;
            case 1:
                std::cout << "\033[2K" << "ERRORE: troppe lettere";
                break;
        }

        return 0;
    }

    else{

        bool is_a_word = false;

        for(int i = 0; i < dict_size; i++){

            bool same = true;

            for(int j = 0; j < 5; j++){

                if(dictionary[i][j] != guess[j]){
                    
                    same = false;
                    break;
                }
            }

            if(same){

                is_a_word = true;
                break;
            }
        }

        if(!is_a_word){

            switch(language){
                case 0:
                    //std::cout << "hello";
                    std::cout << "\033[2K" << "ERROR: not in the word list";
                    break;
                case 1:
                    std::cout << "\033[2K" << "ERRORE: non presente nella lista delle parole";
                    break;
            }
            
            return 0;
        }
    }

    return 1;
}

void printGUESS(int colors[], std::string guess){

    char brackets[2] = {0};

    for(int i = 0; i < 5; i++){

        if(colors[i] == 0){

            // char brackets[3] = "[]";
            brackets[0] = '[';
            brackets[1] = ']';
        }

        else if(colors[i] == 1){

            // char brackets[3] = "()";
            brackets[0] = '(';
            brackets[1] = ')';
        }

        else if(colors[i] == 2){

            // char brackets[3] = "{}";
            brackets[0] = '{';
            brackets[1] = '}';
        }

        printLETTER(guess[i], brackets);
    }
}

void printLETTER(char letter, char brackets[]){
    
    std::cout << brackets[0] << letter << brackets[1] << ' ';
}

